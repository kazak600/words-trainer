"""Generate the topics seed migration of a language from its topic map.

    python3 -I data/pipeline/seed_topics.py            # Latvian: worker/migrations/0003_seed_topics.sql
    python3 -I data/pipeline/seed_topics.py --lang en  # English: topics and the en-uk deck row
"""

import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # python -I drops the script dir

from lang import ROOT, Lang, get_lang


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build_sql(lang: Lang, rows) -> tuple[str, int]:
    topics: dict[str, tuple[str, str]] = {}
    for row in rows:
        topics.setdefault(row["topic_slug"], (row[lang.title_column], row["title_uk"]))

    lines = [
        f"-- Generated by data/pipeline/seed_topics.py from {lang.topic_map.relative_to(ROOT)}. Do not edit.",
        "INSERT INTO topics (lang, slug, title, title_uk) VALUES",
    ]
    values = [
        f"  ({quote(lang.code)}, {quote(slug)}, {quote(title)}, {quote(title_uk)})"
        for slug, (title, title_uk) in topics.items()
    ]
    lines.append(",\n".join(values) + ";")
    if lang.deck:
        slug, source, target, title = lang.deck
        lines.append(
            "INSERT INTO decks (slug, source_lang, target_lang, title) VALUES "
            f"({quote(slug)}, {quote(source)}, {quote(target)}, {quote(title)});"
        )
    return "\n".join(lines) + "\n", len(topics)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--lang", default="lv")
    lang = get_lang(parser.parse_args().lang)
    with lang.topic_map.open(encoding="utf-8", newline="") as f:
        sql, count = build_sql(lang, csv.DictReader(f))
    lang.seed_target.write_text(sql, encoding="utf-8")
    print(f"wrote {count} topics to {lang.seed_target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
