"""Generate worker/migrations/0003_seed_topics.sql from data/topic_map.csv."""

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data" / "topic_map.csv"
TARGET = ROOT / "worker" / "migrations" / "0003_seed_topics.sql"


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    topics: dict[str, tuple[str, str]] = {}
    with SOURCE.open(encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            topics.setdefault(row["topic_slug"], (row["title_lv"], row["title_uk"]))

    lines = [
        "-- Generated by data/pipeline/seed_topics.py from data/topic_map.csv. Do not edit.",
        "INSERT INTO topics (lang, slug, title, title_uk) VALUES",
    ]
    values = [
        f"  ('lv', {quote(slug)}, {quote(title)}, {quote(title_uk)})"
        for slug, (title, title_uk) in topics.items()
    ]
    lines.append(",\n".join(values) + ";")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(topics)} topics to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
